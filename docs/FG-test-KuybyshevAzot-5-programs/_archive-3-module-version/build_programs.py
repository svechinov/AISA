# XML-образцы абзацев (сняты с шаблона, paraId/rsid опущены — они необязательны)
# ----------------------------------------------------------------------------
RPR_CAMBRIA = '<w:rFonts w:ascii="Cambria" w:hAnsi="Cambria" w:cs="Arial"/>'
RPR_BODY = '<w:rFonts w:ascii="Cambria" w:eastAsiaTheme="minorHAnsi" w:hAnsi="Cambria" w:cstheme="minorBidi"/>'
BDR = '<w:bdr w:val="none" w:sz="0" w:space="0" w:color="auto" w:frame="1"/>'
TABS = '<w:tabs><w:tab w:val="left" w:pos="709"/><w:tab w:val="left" w:pos="851"/></w:tabs>'
SPACING = '<w:spacing w:line="276" w:lineRule="auto"/>'
IND = '<w:ind w:left="426"/>'
BULLET_NUMID = "15"  # abstractNum 9 — маркер Symbol, отступ 1146/360


def t(text):
    return '<w:t xml:space="preserve">%s</w:t>' % escape(text)


def p_overtitle(text):
    """Надзаголовок: «Программа развития руководителей» — Cambria, центр, 1F1F1F."""
    return (
        '<w:p><w:pPr>%s%s<w:jc w:val="center"/><w:rPr>%s<w:color w:val="1F1F1F"/></w:rPr></w:pPr>'
        '<w:r><w:rPr>%s<w:bCs/><w:color w:val="1F1F1F"/>%s</w:rPr>%s</w:r></w:p>'
        % (SPACING, IND, RPR_CAMBRIA, RPR_CAMBRIA, BDR, t(text))
    )


def p_title(text):
    """Название программы: Cambria, bold, 16pt, синий 1F497D, центр."""
    return (
        '<w:p><w:pPr>%s%s<w:jc w:val="center"/><w:rPr>%s<w:color w:val="1F497D" w:themeColor="text2"/><w:sz w:val="32"/></w:rPr></w:pPr>'
        '<w:r><w:rPr>%s<w:b/><w:bCs/><w:color w:val="1F497D" w:themeColor="text2"/><w:sz w:val="32"/>%s</w:rPr>%s</w:r></w:p>'
        % (SPACING, IND, RPR_CAMBRIA, RPR_CAMBRIA, BDR, t(text))
    )


def p_empty():
    return (
        '<w:p><w:pPr>%s%s<w:rPr>%s<w:color w:val="1F1F1F"/></w:rPr></w:pPr></w:p>'
        % (SPACING, IND, RPR_CAMBRIA)
    )


def p_empty_bold():
    return (
        '<w:p><w:pPr>%s%s<w:rPr>%s<w:b/><w:bCs/><w:color w:val="1F1F1F"/>%s</w:rPr></w:pPr></w:p>'
        % (SPACING, IND, RPR_CAMBRIA, BDR)
    )


def p_empty_body():
    """Пустой абзац между модулями (в шаблоне — стиль List Paragraph без нумерации)."""
    return (
        '<w:p><w:pPr><w:pStyle w:val="af"/>%s%s%s<w:jc w:val="both"/><w:rPr>%s<w:lang w:eastAsia="en-US"/></w:rPr></w:pPr></w:p>'
        % (TABS, SPACING, IND, RPR_BODY)
    )


def p_label(label, text=""):
    """Абзац «Целевая аудитория: …» — жирная метка + обычный текст, по ширине."""
    runs = '<w:r><w:rPr>%s<w:b/><w:bCs/><w:lang w:eastAsia="en-US"/></w:rPr>%s</w:r>' % (RPR_BODY, t(label))
    if text:
        runs += '<w:r><w:rPr>%s<w:lang w:eastAsia="en-US"/></w:rPr>%s</w:r>' % (RPR_BODY, t(text))
    return (
        '<w:p><w:pPr>%s%s%s<w:jc w:val="both"/><w:rPr>%s<w:lang w:eastAsia="en-US"/></w:rPr></w:pPr>%s</w:p>'
        % (TABS, SPACING, IND, RPR_BODY, runs)
    )


def p_results_label(text):
    """«В результате прохождения тренинга участники:» — в шаблоне это отдельный
    вариант оформления (Cambria/Arial, 1F1F1F, без выравнивания по ширине)."""
    return (
        '<w:p><w:pPr>%s%s<w:rPr>%s<w:color w:val="1F1F1F"/></w:rPr></w:pPr>'
        '<w:r><w:rPr>%s<w:b/><w:bCs/><w:color w:val="1F1F1F"/>%s</w:rPr>%s</w:r></w:p>'
        % (SPACING, IND, RPR_CAMBRIA, RPR_CAMBRIA, BDR, t(text))
    )


def p_bullet(text):
    return (
        '<w:p><w:pPr><w:pStyle w:val="af"/><w:numPr><w:ilvl w:val="0"/><w:numId w:val="%s"/></w:numPr>%s%s<w:jc w:val="both"/>'
        '<w:rPr>%s<w:lang w:eastAsia="en-US"/></w:rPr></w:pPr>'
        '<w:r><w:rPr>%s<w:lang w:eastAsia="en-US"/></w:rPr>%s</w:r></w:p>'
        % (BULLET_NUMID, TABS, SPACING, RPR_BODY, RPR_BODY, t(text))
    )


def p_center_bold(text, page_break_before=False):
    """«Содержание программы:» — с новой страницы через свойство абзаца
    (в отличие от <w:br type="page"/> не порождает пустой лист при плотной
    первой странице)."""
    pbb = "<w:pageBreakBefore/>" if page_break_before else ""
    return (
        '<w:p><w:pPr>%s%s%s<w:jc w:val="center"/><w:rPr>%s<w:color w:val="1F1F1F"/></w:rPr></w:pPr>'
        '<w:r><w:rPr>%s<w:b/><w:bCs/><w:color w:val="1F1F1F"/>%s</w:rPr>%s</w:r></w:p>'
        % (pbb, SPACING, IND, RPR_CAMBRIA, RPR_CAMBRIA, BDR, t(text))
    )


def p_block(text):
    """«Блок №1: …» — Cambria, bold, 14pt, синий."""
    rpr = '%s<w:b/><w:bCs/><w:color w:val="1F497D" w:themeColor="text2"/><w:sz w:val="28"/>%s' % (RPR_CAMBRIA, BDR)
    return (
        '<w:p><w:pPr>%s%s<w:rPr>%s</w:rPr></w:pPr><w:r><w:rPr>%s</w:rPr>%s</w:r></w:p>'
        % (SPACING, IND, rpr, rpr, t(text))
    )


def p_block_gap():
    """Пустой абзац после заголовка блока (в шаблоне — body-абзац, bold)."""
    return (
        '<w:p><w:pPr>%s%s%s<w:jc w:val="both"/><w:rPr>%s<w:b/><w:bCs/><w:lang w:eastAsia="en-US"/></w:rPr></w:pPr></w:p>'
        % (TABS, SPACING, IND, RPR_BODY)
    )


def p_module(text):
    return p_label(text)


# ----------------------------------------------------------------------------
# Сборка документа
# ----------------------------------------------------------------------------
def build_body(prog):
    P = []
    P.append(p_overtitle(prog["overtitle"]))
    P.append(p_title(prog["title"]))
    P.append(p_empty())
    P.append(p_label("Целевая аудитория", ": " + prog["audience"]))
    P.append(p_empty())
    P.append(p_label("Формат проведения программы:"))
    P.extend(p_bullet(x) for x in prog["format"])
    P.append(p_empty())
    P.append(p_label("Цели программы:"))
    P.extend(p_bullet(x) for x in prog["goals"])
    P.append(p_empty())
    P.append(p_label("Задачи тренинга:"))
    P.extend(p_bullet(x) for x in prog["tasks"])
    P.append(p_empty())
    P.append(p_results_label("В результате прохождения тренинга участники:"))
    P.extend(p_bullet(x) for x in prog["results"])
    P.append(p_empty())
    P.append(p_label("Формы работы:", " " + prog["forms"]))
    # --- страница 2: содержание ---
    P.append(p_center_bold("Содержание программы:", page_break_before=True))
    P.append(p_empty_bold())
    for bi, block in enumerate(prog["blocks"]):
        P.append(p_block("Блок №%d: %s" % (bi + 1, block["title"])))
        P.append(p_block_gap())
        for mi, mod in enumerate(block["modules"]):
            P.append(p_module("Модуль №%d. %s" % (mi + 1, mod["title"])))
            P.extend(p_bullet(x) for x in mod["items"])
            if mi < len(block["modules"]) - 1:
                P.append(p_empty_body())
        if bi < len(prog["blocks"]) - 1:
            P.append(p_empty())
    return "".join(P)


def build_document_xml(prog):
    src = open(os.path.join(TPL_DIR, "word", "document.xml"), encoding="utf-8").read()
    head = src[: src.find("<w:body>") + len("<w:body>")]
    sect = src[src.rfind("<w:sectPr") :]  # включает </w:body></w:document>
    return head + build_body(prog) + sect


def write_docx(prog, out_path):
    work = tempfile.mkdtemp(prefix="fg_work_")
    shutil.rmtree(work)
    shutil.copytree(TPL_DIR, work)
    with open(os.path.join(work, "word", "document.xml"), "w", encoding="utf-8") as f:
        f.write(build_document_xml(prog))
    core_p = os.path.join(work, "docProps", "core.xml")
    core = open(core_p, encoding="utf-8").read()
    if "<dc:title>" in core:
        core = re.sub(r"<dc:title>.*?</dc:title>", "<dc:title>%s</dc:title>" % escape(prog["title"]), core, flags=re.S)
    open(core_p, "w", encoding="utf-8").write(core)

    if os.path.exists(out_path):
        os.remove(out_path)
    with zipfile.ZipFile(out_path, "w", zipfile.ZIP_DEFLATED) as z:
        z.write(os.path.join(work, "[Content_Types].xml"), "[Content_Types].xml")
        for root, _dirs, files in os.walk(work):
            for fn in files:
                full = os.path.join(root, fn)
                arc = os.path.relpath(full, work).replace(os.sep, "/")
                if arc == "[Content_Types].xml":
                    continue
                z.write(full, arc)
    shutil.rmtree(work)



# Сборка документа
# ----------------------------------------------------------------------------
def build_body(prog):
    P = [
        p_head_small("Программа тренинга"),
        p_head_title(prog["title"]),
        p_empty(),
        p_goal("Цель", prog["goal"]),
        p_empty(),
        p_results_label("В результате прохождения тренинга участники:"),
        p_empty(),
    ]
    P.extend(p_result_bullet(x) for x in prog["results"])
    P.append(p_empty())
    P.append(p_label_text("Формы работы:", prog["forms"]))
    P.append(p_empty())
    P.append(p_label_text("Продолжительность:", prog.get("duration", "2 тренинг-дня.")))
    P.append(p_empty())
    P.append(p_contents_title("Содержание программы:"))
    P.append(p_empty())
    for mi, mod in enumerate(prog["modules"]):
        P.append(p_module_title("Модуль №%d. %s" % (mi + 1, mod["title"])))
        items = mod["items"]
        for k, item in enumerate(items):
            P.append(p_module_bullet(item, keep_next=(k < len(items) - 1)))
        if mi < len(prog["modules"]) - 1:
            P.append(p_empty())
    return "".join(P)


def build_document_xml(prog):
    src = open(os.path.join(TPL_DIR, "word", "document.xml"), encoding="utf-8").read()
    head = src[: src.find("<w:body>") + len("<w:body>")]
    sect = src[src.rfind("<w:sectPr"):]
    return head + build_body(prog) + sect


def write_docx(prog, out_path):
    work = tempfile.mkdtemp(prefix="fg_work_")
    shutil.rmtree(work)
    shutil.copytree(TPL_DIR, work)
    with open(os.path.join(work, "word", "document.xml"), "w", encoding="utf-8") as f:
        f.write(build_document_xml(prog))
    core_p = os.path.join(work, "docProps", "core.xml")
    if os.path.exists(core_p):
        core = open(core_p, encoding="utf-8").read()
        if "<dc:title>" in core:
            core = re.sub(r"<dc:title>.*?</dc:title>", "<dc:title>%s</dc:title>" % escape(prog["title"]), core, flags=re.S)
        open(core_p, "w", encoding="utf-8").write(core)
    if os.path.exists(out_path):
        os.remove(out_path)
    with zipfile.ZipFile(out_path, "w", zipfile.ZIP_DEFLATED) as z:
        z.write(os.path.join(work, "[Content_Types].xml"), "[Content_Types].xml")
        for root, _dirs, files in os.walk(work):
            for fn in files:
                full = os.path.join(root, fn)
                arc = os.path.relpath(full, work).replace(os.sep, "/")
                if arc == "[Content_Types].xml":
                    continue
                z.write(full, arc)
    shutil.rmtree(work)



F_REG = '<w:rFonts w:ascii="Barnaul Grotesk" w:hAnsi="Barnaul Grotesk"/>'
F_REG_T = '<w:rFonts w:ascii="Barnaul Grotesk" w:hAnsi="Barnaul Grotesk" w:cs="Tahoma"/>'
F_BOLD = '<w:rFonts w:ascii="Barnaul Grotesk Bold" w:hAnsi="Barnaul Grotesk Bold"/>'
F_BOLD_T = '<w:rFonts w:ascii="Barnaul Grotesk Bold" w:hAnsi="Barnaul Grotesk Bold" w:cs="Tahoma"/>'
F_LIST = '<w:rFonts w:ascii="Barnaul Grotesk" w:eastAsiaTheme="minorHAnsi" w:hAnsi="Barnaul Grotesk" w:cstheme="minorBidi"/>'
BLACK = '<w:color w:val="000000" w:themeColor="text1"/>'
TABS4 = ('<w:tabs><w:tab w:val="left" w:pos="567"/><w:tab w:val="left" w:pos="709"/>'
         '<w:tab w:val="left" w:pos="851"/><w:tab w:val="left" w:pos="993"/></w:tabs>')
TABS2 = '<w:tabs><w:tab w:val="left" w:pos="567"/><w:tab w:val="left" w:pos="709"/></w:tabs>'
TABS_LIST = '<w:tabs><w:tab w:val="left" w:pos="709"/><w:tab w:val="left" w:pos="851"/></w:tabs>'
TABS_MOD = ('<w:tabs><w:tab w:val="clear" w:pos="720"/><w:tab w:val="left" w:pos="567"/>'
            '<w:tab w:val="left" w:pos="709"/><w:tab w:val="left" w:pos="851"/>'
            '<w:tab w:val="left" w:pos="993"/><w:tab w:val="left" w:pos="7237"/></w:tabs>')
IND = '<w:ind w:left="284"/>'
NUM_RESULTS = "5"   # Wingdings-стрелка, отступ 1004/360 (как в образце)
NUM_MODULES = "6"   # Symbol-точка, отступ 720/360 (как в образце)


def t(text):
    return '<w:t xml:space="preserve">%s</w:t>' % escape(text)


def run(rpr, text):
    return '<w:r><w:rPr>%s</w:rPr>%s</w:r>' % (rpr, t(text))


def p_head_small(text):
    rpr = F_REG + '<w:b/>' + BLACK
    return '<w:p><w:pPr>%s%s<w:jc w:val="center"/><w:rPr>%s</w:rPr></w:pPr>%s</w:p>' % (TABS4, IND, rpr, run(rpr, text))


def p_head_title(text):
    rpr = F_BOLD + '<w:b/>' + BLACK
    return '<w:p><w:pPr>%s%s<w:jc w:val="center"/><w:rPr>%s</w:rPr></w:pPr>%s</w:p>' % (TABS4, IND, rpr, run(rpr, text))


def p_empty():
    return '<w:p><w:pPr>%s%s<w:jc w:val="both"/><w:rPr>%s%s</w:rPr></w:pPr></w:p>' % (TABS2, IND, F_REG_T, BLACK)


def p_goal(label, text):
    ppr = ('%s<w:autoSpaceDE w:val="0"/><w:autoSpaceDN w:val="0"/><w:adjustRightInd w:val="0"/>%s'
           '<w:jc w:val="both"/><w:rPr>%s%s</w:rPr>' % (TABS2, IND, F_REG_T, BLACK))
    runs = (run(F_BOLD_T + '<w:b/><w:bCs/>' + BLACK, label)
            + run(F_REG_T + '<w:b/><w:bCs/>' + BLACK, ':')
            + run(F_REG_T + BLACK, ' ' + text))
    return '<w:p><w:pPr>%s</w:pPr>%s</w:p>' % (ppr, runs)


def p_results_label(text):
    rpr = F_BOLD_T + '<w:b/><w:bCs/><w:iCs/>' + BLACK
    return '<w:p><w:pPr>%s%s<w:jc w:val="both"/><w:rPr>%s</w:rPr></w:pPr>%s</w:p>' % (TABS4, IND, rpr, run(rpr, text))


def p_result_bullet(text):
    rpr = F_LIST + '<w:lang w:eastAsia="en-US"/>'
    return ('<w:p><w:pPr><w:pStyle w:val="af"/><w:numPr><w:ilvl w:val="0"/><w:numId w:val="%s"/></w:numPr>%s'
            '<w:jc w:val="both"/><w:rPr>%s</w:rPr></w:pPr>%s</w:p>' % (NUM_RESULTS, TABS_LIST, rpr, run(rpr, text)))


def p_label_text(label, text):
    ppr = '<w:tabs><w:tab w:val="left" w:pos="567"/></w:tabs>%s<w:jc w:val="both"/><w:rPr>%s<w:bCs/>%s</w:rPr>' % (IND, F_REG, BLACK)
    runs = run(F_BOLD + '<w:b/>' + BLACK, label) + run(F_REG + '<w:bCs/>' + BLACK, ' ' + text)
    return '<w:p><w:pPr>%s</w:pPr>%s</w:p>' % (ppr, runs)


def p_contents_title(text):
    rpr = F_BOLD + '<w:b/><w:bCs/>' + BLACK + '<w:sz w:val="24"/><w:szCs w:val="24"/>'
    ppr = ('<w:pStyle w:val="aa"/><w:tabs><w:tab w:val="left" w:pos="0"/><w:tab w:val="left" w:pos="567"/>'
           '<w:tab w:val="left" w:pos="709"/><w:tab w:val="left" w:pos="851"/><w:tab w:val="left" w:pos="993"/></w:tabs>'
           '%s<w:jc w:val="center"/><w:rPr>%s</w:rPr>' % (IND, rpr))
    return '<w:p><w:pPr>%s</w:pPr>%s</w:p>' % (ppr, run(rpr, text))


def p_module_title(text):
    rpr = F_BOLD_T + '<w:b/><w:bCs/>' + BLACK
    return ('<w:p><w:pPr><w:pStyle w:val="af"/><w:keepNext/>%s%s<w:jc w:val="both"/><w:rPr>%s</w:rPr></w:pPr>%s</w:p>'
            % (TABS2, IND, rpr, run(rpr, text)))


def p_module_bullet(text, keep_next):
    rpr = F_REG_T + BLACK
    kn = '<w:keepNext/>' if keep_next else ''
    return ('<w:p><w:pPr>%s<w:numPr><w:ilvl w:val="0"/><w:numId w:val="%s"/></w:numPr>%s'
            '<w:jc w:val="both"/><w:rPr>%s</w:rPr></w:pPr>%s</w:p>' % (kn, NUM_MODULES, TABS_MOD, rpr, run(rpr, text)))


